#include "cub3D.h"

void	free_matrix(char **matrix)
{
	int	i;

	i = 0;
	if (!matrix)
		return ;
	while (matrix[i])
	{
		free(matrix[i]);
		i++;
	}
	free(matrix);
}

void	drain_gnl(int fd)
{
	char	*tmp;

	tmp = get_next_line(fd);
	while (tmp)
	{
		free(tmp);
		tmp = get_next_line(fd);
	}
}

void	free_textures_paths(t_game *g)
{
	int	i;

	i = 0;
	while (i < 4)
	{
		if (g->tex_path[i])
			free(g->tex_path[i]);
		i++;
	}
}
